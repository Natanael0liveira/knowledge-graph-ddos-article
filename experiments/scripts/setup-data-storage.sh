#!/usr/bin/env bash
#
# setup-data-storage.sh
#
# Creates the directory tree on the external drive and writes the .env that
# points the repository to that data root.
#
# Usage:
#   ./scripts/setup-data-storage.sh /Volumes/YourDrive/kg-ddos-data
#
# Or through an environment variable:
#   export DATA_ROOT=/Volumes/YourDrive/kg-ddos-data
#   ./scripts/setup-data-storage.sh
#

set -euo pipefail

# ---- argument ----
DATA_ROOT="${1:-${DATA_ROOT:-}}"
if [[ -z "$DATA_ROOT" ]]; then
    echo "ERROR: give the path of the data directory."
    echo "Usage: $0 /Volumes/YourDrive/kg-ddos-data"
    exit 1
fi

# Resolve the absolute path. The parent directory must exist: when the drive is not
# mounted, stop here instead of creating the tree somewhere else.
PARENT_DIR="$(dirname "$DATA_ROOT")"
if [[ ! -d "$PARENT_DIR" ]]; then
    echo "ERROR: $PARENT_DIR does not exist. Mount the drive, or create that directory, first."
    exit 1
fi
DATA_ROOT="$(cd "$PARENT_DIR" && pwd)/$(basename "$DATA_ROOT")"

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

echo "=== Directory setup for the experiments ==="
echo "Repository:  $REPO_ROOT"
echo "Data root:   $DATA_ROOT"
echo ""

# ---- create the tree on the external drive ----
echo "[1/4] Creating the tree in $DATA_ROOT..."

mkdir -p "$DATA_ROOT"/{raw,processed,synth,kg,results,logs}
mkdir -p "$DATA_ROOT"/raw/{cicids2017,cic-iot-2023,rt-iot-2022,bccc-cpacket}
mkdir -p "$DATA_ROOT"/processed/{ja4,flows,sessions,clusters}
mkdir -p "$DATA_ROOT"/synth/{distributions,scenarios}
mkdir -p "$DATA_ROOT"/synth/scenarios/{A,B,C}
mkdir -p "$DATA_ROOT"/kg/{fuseki-tdb2,exports}
mkdir -p "$DATA_ROOT"/results/{raw,aggregated,figures}

echo "    OK."

# ---- check the free space ----
echo ""
echo "[2/4] Checking the free space..."
FREE_GB=$(df -g "$DATA_ROOT" | awk 'NR==2 {print $4}')
echo "    Free space found: ${FREE_GB} GB"

if [[ "$FREE_GB" -lt 100 ]]; then
    echo ""
    echo "    WARNING: we recommend at least 100 GB free for all the sprints."
    echo "    You have $FREE_GB GB. You can go on, but Sprint 5 may run short of space."
fi

# ---- write .env ----
echo ""
echo "[3/4] Writing $REPO_ROOT/experiments/.env..."

cat > "$REPO_ROOT/experiments/.env" <<EOF
# Generated by scripts/setup-data-storage.sh on $(date)
# Do NOT commit (already in .gitignore).
DATA_ROOT=$DATA_ROOT
EOF

echo "    OK."

# ---- create the symlink ----
echo ""
echo "[4/4] Creating the symlink experiments/data → $DATA_ROOT..."

# Remove an old symlink, if there is one
if [[ -L "$REPO_ROOT/experiments/data" ]]; then
    rm "$REPO_ROOT/experiments/data"
fi

# Create no symlink if a regular directory is there
if [[ -d "$REPO_ROOT/experiments/data" && ! -L "$REPO_ROOT/experiments/data" ]]; then
    echo "    WARNING: $REPO_ROOT/experiments/data exists as a regular directory."
    echo "    Skipping the symlink. Reach the drive directly at $DATA_ROOT."
else
    ln -s "$DATA_ROOT" "$REPO_ROOT/experiments/data"
    echo "    OK."
fi

echo ""
echo "=== Setup done ==="
echo ""
echo "Check:"
echo "  cat $REPO_ROOT/experiments/.env"
echo "  ls -la $REPO_ROOT/experiments/data/"
echo ""
echo "Sprint 1's Fuseki targets also need FUSEKI_DB in .env (see experiments/.env.example)."
echo ""
echo "Next step: the Python environment."
echo "  cd $REPO_ROOT/experiments"
echo "  python3 -m venv .venv"
echo "  source .venv/bin/activate"
echo "  pip install -r requirements.txt"
echo ""
echo "Then: cd sprint-1 && make help"
